
package com.example.task310.repository;

import java.util.List;
import java.util.Optional;

// Обобщённый интерфейс репозитория.
// Определяет единый набор операций для работы с объектами разных типов.
// Параметр T позволяет использовать этот интерфейс для Editor, Topic,
// Marker и Reaction без дублирования одинаковых методов.
public interface InMemoryRepository<T> {

    // Получение списка всех объектов из хранилища.
    List<T> findAll();

    // Поиск объекта по идентификатору.
    // Optional позволяет вернуть отсутствие объекта без null.
    Optional<T> findById(Long id);

    // Сохранение нового или обновлённого объекта.
    // Возвращает сохранённый объект, в том числе с присвоенным идентификатором.
    T save(T entity);

    // Удаление объекта по идентификатору.
    // Возвращает true, если объект был найден и удалён.
    // Если объект отсутствует, возвращает false.
    boolean deleteById(Long id);

    // Проверка существования объекта с указанным идентификатором.
    // Возвращает true, если объект найден, иначе false.
    boolean existsById(Long id);
}
